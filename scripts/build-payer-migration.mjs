#!/usr/bin/env node
// Turns the APPROVED insurance plan proposal
// (supabase/reference/payer-sources/payer-proposal.csv, reviewed by the user
// 2026-10-11) into a numbered migration of plain inserts into
// insurance_payers. Rows already listed (by migration 003, nationally or in
// that state) are skipped; any other clash on (name, state), such as a
// Medicare Advantage brand the monthly import already added, is left as it is.
//
// Run: node scripts/build-payer-migration.mjs [proposal.csv] [out.sql]

import { readFileSync, writeFileSync } from 'node:fs';
import { objects } from './lib/payers.mjs';

const IN = process.argv[2] || 'supabase/reference/payer-sources/payer-proposal.csv';
const OUT = process.argv[3] || 'supabase/migrations/034_insurance_payers_state_plans.sql';
const SORT = 70;                    // after 003's state plans (50 to 64), before self-pay (900)
const CATS = new Set(['commercial', 'marketplace', 'medicaid']);

const rows = objects(readFileSync(IN, 'utf8')).filter(r => r.state && r.brand && r.already_listed !== 'yes');
for (const r of rows) {
  if (!/^[A-Z]{2}$/.test(r.state)) throw new Error(`bad state "${r.state}"`);
  if (!CATS.has(r.category)) throw new Error(`bad category "${r.category}" for ${r.brand}`);
  if (r.brand === '-') throw new Error(`excluded brand left in the proposal (${r.state})`);
  if (/[|]/.test(r.brand)) throw new Error(`"${r.brand}" (${r.state}) contains "|"; a plan name is one name`);
}
const seen = new Set();
for (const r of rows) { const k = r.state + '|' + r.brand.toLowerCase(); if (seen.has(k)) throw new Error(`duplicate ${k}`); seen.add(k); }

const q = s => "'" + String(s).replace(/'/g, "''") + "'";
rows.sort((a, b) => a.state.localeCompare(b.state) || a.brand.localeCompare(b.brand));
const values = rows.map(r => `  (${q(r.brand)}, ${q(r.state)}, ${q(r.category)}, ${SORT})`).join(',\n');
const by = c => rows.filter(r => r.category === c).length;
writeFileSync(OUT, `-- State insurance plans: private, employer and ACA marketplace insurers (CMS
-- Medical Loss Ratio filings, 2024) and comprehensive Medicaid managed care
-- plans (data.medicaid.gov, 2024) with at least 1,000 members in the state.
-- Generated by scripts/build-payer-migration.mjs from
-- supabase/reference/payer-sources/payer-proposal.csv after the user's review
-- (2026-10-11: approved, non-medical carriers removed, duplicate names merged
-- through supabase/reference/payer-brand-map.csv). Do not edit by hand.
--
-- ${rows.length} rows: ${by('commercial')} commercial, ${by('marketplace')} marketplace, ${by('medicaid')} medicaid.
-- Plans already listed by 003 are not repeated. A row that already exists
-- (same name and state) is left alone, so a re-run is safe.
--
-- Run in the Supabase SQL editor.

insert into public.insurance_payers (name, state, category, sort_order) values
${values}
on conflict (name, state) do nothing;
`);
console.log(`wrote ${OUT}: ${rows.length} rows`);
