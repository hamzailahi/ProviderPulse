// Builds v2/assets/hospital-campuses.js from the reviewed list
// supabase/reference/hospital-campuses.csv (2026-10-25, the user's choice).
//
// Some hospital campuses have no hospital NPI of their own: they bill under a
// parent hospital's NPI at another address, so NPPES (and our directory) lists
// the site only by something else there, such as its pharmacy. Baptist
// Memorial Hospital-Collierville is one: NPPES has only pharmacy NPI
// 1184319667 at 1500 W Poplar Ave, and the hospital bills under the Memphis
// NPI 1578527172. Patients searching Emergency rooms & hospitals never saw it.
// Every row here is checked by hand (the source column says how); nothing is
// inferred from names. Run with --check in CI: a stale or hand-edited asset
// fails the build.
import { readFileSync, writeFileSync } from 'node:fs';
import { parseCsv } from './lib/taxonomy-map.mjs';

const SRC = 'supabase/reference/hospital-campuses.csv', OUT = 'v2/assets/hospital-campuses.js';
const COLS = ['id', 'name', 'address', 'city', 'state', 'zip', 'latitude', 'longitude', 'phone', 'taxonomy_code', 'billing_npi', 'billing_name', 'emergency', 'source', 'verified_on'];

function luhnNpi(npi) {
  if (!/^\d{10}$/.test(npi)) return false;
  let sum = 24;
  const d = npi.slice(0, 9).split('').reverse();
  for (let i = 0; i < 9; i++) { let x = +d[i]; if (i % 2 === 0) { x *= 2; if (x > 9) x -= 9; } sum += x; }
  return (10 - (sum % 10)) % 10 === +npi[9];
}

export function parseCampuses(text, hospitalCodes) {
  const rows = parseCsv(text);
  const head = rows.shift() || [];
  if (head.join(',') !== COLS.join(',')) throw new Error(`${SRC}: header must be ${COLS.join(',')}`);
  const seen = new Set();
  return rows.map((r, n) => {
    const o = Object.fromEntries(COLS.map((c, i) => [c, String(r[i] ?? '').trim()]));
    const bad = m => { throw new Error(`${SRC} row ${n + 2} (${o.id || '?'}): ${m}`); };
    if (!/^[a-z0-9-]{3,60}$/.test(o.id)) bad('id must be lowercase letters, digits and dashes');
    if (seen.has(o.id)) bad('duplicate id'); seen.add(o.id);
    for (const c of ['name', 'address', 'city', 'source', 'billing_name']) if (!o[c]) bad(`${c} is required`);
    if (!/^[A-Z]{2}$/.test(o.state)) bad('state must be a 2-letter code');
    if (!/^\d{5}$/.test(o.zip)) bad('zip must be 5 digits');
    const lat = Number(o.latitude), lng = Number(o.longitude);
    if (!(lat > 17 && lat < 72 && lng > -180 && lng < -64)) bad('latitude/longitude must be a US point');
    if (o.phone && !/^\d{10}$/.test(o.phone)) bad('phone must be 10 digits');
    if (!hospitalCodes.has(o.taxonomy_code)) bad(`taxonomy_code ${o.taxonomy_code} is not in the Emergency rooms & hospitals door`);
    if (!luhnNpi(o.billing_npi)) bad('billing_npi is not a valid NPI');
    if (!['yes', 'no'].includes(o.emergency)) bad('emergency must be yes or no');
    if (!/^\d{4}-\d{2}-\d{2}$/.test(o.verified_on)) bad('verified_on must be YYYY-MM-DD');
    return { id: o.id, name: o.name, address: o.address, city: o.city, state: o.state, zip: o.zip, lat, lng,
      phone: o.phone || null, taxonomy_code: o.taxonomy_code, billing_npi: o.billing_npi, billing_name: o.billing_name, emergency: o.emergency === 'yes' };
  });
}

export function renderAsset(list) {
  return `// GENERATED by scripts/build-hospital-campuses.mjs from
// supabase/reference/hospital-campuses.csv. Do not edit by hand.
// Hospital campuses with no hospital NPI of their own (they bill under a
// parent hospital's NPI elsewhere), so patient search can still find them.
(function (root) {
  var LIST = ${JSON.stringify(list, null, 2)};
  // Campuses inside a {s, n, w, e} box, shaped like directory rows.
  function inBox(b) {
    return LIST.filter(function (c) { return c.lat >= b.s && c.lat <= b.n && c.lng >= b.w && c.lng <= b.e; }).map(function (c) {
      return { npi: 'campus-' + c.id, name: c.name, address: c.address, city: c.city, state: c.state, zip: c.zip,
        latitude: c.lat, longitude: c.lng, phone: c.phone, taxonomy_code: c.taxonomy_code, primary_taxonomy: 'Hospital campus',
        _src: 'campus', campus: { billing_npi: c.billing_npi, billing_name: c.billing_name, emergency: c.emergency } };
    });
  }
  var api = { list: LIST, inBox: inBox };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.HospitalCampuses = api;
})(typeof window !== 'undefined' ? window : this);
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { createRequire } = await import('node:module');
  const TaxonomyMap = createRequire(import.meta.url)('../v2/assets/taxonomy-map.js');
  const codes = new Set(TaxonomyMap.codesForCare('Emergency rooms & hospitals'));
  const out = renderAsset(parseCampuses(readFileSync(SRC, 'utf8'), codes));
  if (process.argv.includes('--check')) {
    let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (cur !== out) { console.error(`${OUT} is stale or hand-edited; run node scripts/build-hospital-campuses.mjs`); process.exit(1); }
    console.log(`${OUT} is current`);
  } else { writeFileSync(OUT, out); console.log(`wrote ${OUT}`); }
}
